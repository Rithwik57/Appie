import { CirclePause, TriangleAlert } from 'lucide-react';
import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { selectAuditFor, selectDemoIdentity, selectEpisode, selectReviewer } from '../../app/selectors';
import { useAppState, useDispatch } from '../../app/store';
import { isNoteRequired } from '../../app/validation';
import { CONCERN_LABELS, DOCTOR_DECISION_LABELS, DURATION_LABELS, REVIEWER_APPROVED_GUIDANCE, SEVERITY_LABELS, SIMULATED_CARE_PLAN_VARIANTS, WARNING_LABELS } from '../../domain/copy';
import { STATUS_META } from '../../domain/status';
import type { DoctorDecisionType } from '../../domain/types';
import { allowedDoctorDecisions } from '../../review/gates';
import { AuditList, Button, DataList, EmptyState, ErrorSummary, LinkButton, Notice, PageHeader, QuickReplyGroup, ReviewerCard, Section, SelectField, SimulatedTag, StatusChip, TextArea } from '../components/ui';
import { CATEGORY_META } from '../components/categoryMeta';
import { useEpisodeFromParams } from '../patient/hooks';

export const DoctorCasePage = () => {
  const state = useAppState();
  const dispatch = useDispatch();
  const episode = useEpisodeFromParams();
  const [error, setError] = useState<string | null>(null);
  if (!episode) return <EmptyState title="Case unavailable" action={<LinkButton to="/doctor">Back to review queue</LinkButton>}>Choose a case in the review queue.</EmptyState>;
  const doctor = state.reviewers.find((reviewer) => reviewer.role === 'doctor') ?? null;
  const canStart = ['awaiting_doctor_review', 'teleconsult_requested', 'pharmacist_flagged'].includes(episode.status);
  const open = () => {
    const result = dispatch({ type: 'START_REVIEW', episodeId: episode.id });
    setError(result.ok ? null : result.error.message);
  };
  const intake = episode.intake;
  const category = episode.assessment ? CATEGORY_META[episode.assessment.category] : null;
  const flag = episode.pharmacistChecks.at(-1);
  return (
    <div className="page">
      <PageHeader eyebrow={`Case ${episode.id}`} title="Sample doctor review" description={`Patient: ${state.patient.displayName}`} meta={<StatusChip status={episode.status} />} actions={<LinkButton variant="ghost" to="/doctor">Back to review queue</LinkButton>} />
      <ErrorSummary message={error} />
      <div className="grid grid--case">
        <div className="stack">
          <Section title="Patient-entered demo intake">
            <DataList items={[
              { label: 'Main concern', value: intake.concernArea ? CONCERN_LABELS[intake.concernArea] : 'Not provided' },
              { label: 'Duration', value: intake.duration ? DURATION_LABELS[intake.duration] : 'Not provided' },
              { label: 'Severity', value: intake.severity ? SEVERITY_LABELS[intake.severity] : 'Not provided' },
              { label: 'Warning sign check', value: intake.warningSigns ? WARNING_LABELS[intake.warningSigns] : 'Not provided' },
              { label: 'Additional context', value: intake.freeText || 'None provided' },
            ]} />
          </Section>
          {episode.assessment && (
            <Section title={<>Preliminary AI summary <SimulatedTag>Simulated</SimulatedTag></>}>
              {category && <p className="category"><category.icon size={18} aria-hidden="true" /><strong>{category.label}</strong> · simulated confidence {episode.assessment.simulatedConfidence}</p>}
              <p>{episode.assessment.summary}</p>
              <p className="hint">Not a diagnosis. Generated by a local mock service for demonstration.</p>
            </Section>
          )}
          {episode.moreInfo.length > 0 && (
            <Section title="More information exchange">
              {episode.moreInfo.map((item) => <p key={item.askedAt}>Question: {item.question}<br />Response: {item.response ?? 'Awaiting patient response'}</p>)}
            </Section>
          )}
          {flag?.outcome === 'flagged_to_doctor' && <Notice tone="warning" icon={TriangleAlert} title="Pharmacist flag" headingLevel={2}><p>{flag.reason} <SimulatedTag>Demo</SimulatedTag></p></Notice>}
        </div>
        <div className="stack">
          <Section title="Reviewer">
            <ReviewerCard reviewer={selectReviewer(state, doctor?.id ?? null)} />
            <p className="hint">Viewing as {selectDemoIdentity(state, 'doctor').displayName} (demo identity).</p>
          </Section>
          {episode.status === 'escalated_urgent' ? (
            <Notice tone="urgent" icon={CirclePause} title="Routine flow paused" headingLevel={2}>
              <p>This case is escalated. Routine approval, pharmacist check and fulfillment are unavailable. The patient is shown emergency and in-person-care guidance.</p>
            </Notice>
          ) : episode.status === 'in_doctor_review' ? (
            <DecisionForm episodeId={episode.id} />
          ) : (
            <Section title="Review status">
              <p>{STATUS_META[episode.status].patientSummary}</p>
              {canStart && <Button onClick={open}>Start review</Button>}
            </Section>
          )}
        </div>
      </div>
      <AuditList audit={selectAuditFor(state, episode.id)} />
    </div>
  );
};

export const DecisionForm = ({ episodeId }: { episodeId: string }) => {
  const state = useAppState();
  const dispatch = useDispatch();
  const navigate = useNavigate();
  const episode = selectEpisode(state, episodeId)!;
  const [decision, setDecision] = useState<DoctorDecisionType>('approve_with_prescription');
  const [guidance, setGuidance] = useState<string>(REVIEWER_APPROVED_GUIDANCE);
  const [note, setNote] = useState('Sample doctor review note.');
  const [error, setError] = useState<string | null>(null);
  const [guidanceError, setGuidanceError] = useState<string | null>(null);
  const [noteError, setNoteError] = useState<string | null>(null);
  const allowed = allowedDoctorDecisions(episode);
  if (allowed.length === 0) return <Notice tone="blocked" title="Decisions unavailable" headingLevel={2}><p>Routine decisions are unavailable for this status.</p></Notice>;
  const guidanceRequired = ['approve_with_prescription', 'finalize_without_prescription'].includes(decision);
  const noteRequired = isNoteRequired(decision, guidanceRequired && guidance !== REVIEWER_APPROVED_GUIDANCE && (SIMULATED_CARE_PLAN_VARIANTS as readonly string[]).includes(guidance), episode);
  const submit = () => {
    const result = dispatch({ type: 'DOCTOR_DECIDE', episodeId, decision, guidance: guidanceRequired ? guidance : null, note });
    if (result.ok) {
      navigate('/doctor', { state: { toast: 'Sample doctor decision saved.' } });
      return;
    }
    setGuidanceError(result.error.fieldErrors?.guidance ?? null);
    setNoteError(result.error.fieldErrors?.note ?? null);
    setError(result.error.fieldErrors ? null : result.error.message);
  };
  return (
    <section className="card decision" aria-labelledby="decision-title">
      <h2 id="decision-title">Record a sample doctor decision</h2>
      <p className="hint">These are simulated clinical workflow decisions, not real medical guidance.</p>
      <ErrorSummary message={error} />
      <QuickReplyGroup legend="Decision" options={allowed.map((value) => ({ value, label: DOCTOR_DECISION_LABELS[value] }))} value={decision} onChange={(value) => { setDecision(value as DoctorDecisionType); setError(null); }} />
      {guidanceRequired && (
        <>
          <SelectField
            id="care-plan-variant"
            label="Edit simulated care-plan variant"
            hint="Choose from these safe, non-clinical demonstration variants. A review note is required for an edited variant."
            value={guidance}
            onChange={(value) => { setGuidance(value); setGuidanceError(null); }}
            options={SIMULATED_CARE_PLAN_VARIANTS.map((variant, index) => ({ value: variant, label: index === 0 ? 'Default simulated care plan' : `Edited simulated care-plan variant ${index}` }))}
            error={guidanceError}
          />
          <p className="quote">Selected simulated, non-clinical care plan: {guidance}</p>
        </>
      )}
      <TextArea label="Review note / reason" hint={noteRequired ? 'Required for this decision (at least 10 characters). Recorded in the audit history.' : undefined} required={noteRequired} value={note} onChange={(value) => { setNote(value); setNoteError(null); }} error={noteError ?? undefined} maxLength={1000} />
      <div className="actions"><Button onClick={submit}>Save sample doctor decision</Button></div>
    </section>
  );
};
